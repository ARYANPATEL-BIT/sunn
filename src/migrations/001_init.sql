-- Sunn's schema as it was in SQLite when it moved to Postgres. Timestamps stay ISO 8601 text in
-- UTC and flags stay 0/1 integers, as they were, so the code that reads them is unchanged.
-- The language CHECKs list languages.CODES; adding a language means a new migration
-- (tests/test_database.py checks the two agree).

-- email is stored lowercased; password_hash is argon2. language is the one the user speaks,
-- what Prisma hears them in and new phrases are written in.
-- voice_embedding is Gnani's speaker_embedding as JSON, set only after voice consent.
-- caregiver_phone is digits only, country code first, ready for a wa.me link.
CREATE TABLE users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    language TEXT NOT NULL CHECK (language IN ('en', 'hi', 'ta', 'te', 'kn', 'ml', 'mr', 'gu', 'bn', 'pa')),
    consent_given_at TEXT NOT NULL,
    voice_embedding TEXT,
    voice_consent_given_at TEXT,
    use_own_voice INTEGER NOT NULL DEFAULT 0,
    caregiver_name TEXT,
    caregiver_phone TEXT,
    google_id TEXT,
    phrase_goal INTEGER
);

-- contexts is comma separated: home, hospital, market, or any. language is the one the phrase
-- is in: Timbre says it in that language, and it is matched only to recordings in it (or English).
CREATE TABLE phrases (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id),
    text TEXT NOT NULL,
    contexts TEXT NOT NULL DEFAULT 'any',
    urgent INTEGER NOT NULL DEFAULT 0,
    language TEXT CHECK (language IN ('en', 'hi', 'ta', 'te', 'kn', 'ml', 'mr', 'gu', 'bn', 'pa'))
);

-- A word that fills a template's slot, like पानी in "{item} चाहिए".
CREATE TABLE slot_words (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id),
    slot TEXT NOT NULL CHECK (slot IN ('item', 'person', 'place')),
    text TEXT NOT NULL
);

-- text has one slot, at its start or end; fixed_part is the rest, recorded on its own.
CREATE TABLE templates (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id),
    text TEXT NOT NULL,
    fixed_part TEXT NOT NULL
);

-- A recognition is stored with phrase_id and source NULL; confirming it sets both, which adds
-- it to the phrase bank. top1_phrase_id is the best candidate at recognition time, kept for the
-- top-1 hit rate. An enrollment belongs to exactly one of phrase_id, slot_word_id or
-- template_id. language is the user's language when Prisma transcribed it. speech_source is
-- where a demo recording came from (scripts/load_demo.py); NULL for one recorded in the app.
-- audio_path is on the server's disk, which may have been wiped since (docs/DEPLOY.md): only
-- prisma_hypothesis is used for matching.
CREATE TABLE samples (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id),
    phrase_id INTEGER REFERENCES phrases(id),
    audio_path TEXT NOT NULL,
    prisma_hypothesis TEXT NOT NULL,
    source TEXT CHECK (source IN ('enroll', 'correction')),
    top1_phrase_id INTEGER REFERENCES phrases(id),
    created_at TEXT NOT NULL,
    slot_word_id INTEGER REFERENCES slot_words(id),
    template_id INTEGER REFERENCES templates(id),
    language TEXT CHECK (language IN ('en', 'hi', 'ta', 'te', 'kn', 'ml', 'mr', 'gu', 'bn', 'pa')),
    speech_source TEXT CHECK (speech_source IN ('pilot', 'torgo', 'simulated'))
);

-- One row per confirmed recognition, for the usage priors.
CREATE TABLE uses (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id),
    phrase_id INTEGER NOT NULL REFERENCES phrases(id),
    created_at TEXT NOT NULL
);

-- One row per Gnani request, sent or answered from the cache. user_id is who it was for; NULL
-- for a script, and set to NULL when the account is deleted. quota is the daily limit a sent call
-- counts against (stt, tts or enroll, see gnani.LIMITS); NULL for a cached call, a retry or a script.
CREATE TABLE api_calls (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind TEXT NOT NULL CHECK (kind IN ('stt', 'tts', 'clone')),
    cached INTEGER NOT NULL,
    audio_seconds DOUBLE PRECISION,
    created_at TEXT NOT NULL,
    user_id INTEGER,
    quota TEXT
);

-- Trainings progress: each lesson started, step index, when finished, and last update. id is
-- the order rows were first made, the tie-break for the lesson to resume.
CREATE TABLE training_progress (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id),
    lesson_id TEXT NOT NULL,
    step_index INTEGER NOT NULL,
    completed_at TEXT,
    updated_at TEXT NOT NULL,
    UNIQUE (user_id, lesson_id)
);

-- Attempts at recorded training steps.
CREATE TABLE training_attempts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id),
    lesson_id TEXT NOT NULL,
    step_id TEXT NOT NULL,
    item_id TEXT,
    transcript TEXT,
    similarity DOUBLE PRECISION,
    wpm INTEGER,
    checked INTEGER NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL
);

-- User reflections at the end of lessons.
CREATE TABLE training_reflections (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id),
    lesson_id TEXT NOT NULL,
    step_id TEXT NOT NULL,
    feeling TEXT NOT NULL,
    created_at TEXT NOT NULL
);

-- Seconds practised per user per day.
CREATE TABLE training_minutes (
    user_id INTEGER NOT NULL REFERENCES users(id),
    day TEXT NOT NULL,
    seconds INTEGER NOT NULL,
    UNIQUE (user_id, day)
);

-- Postgres doesn't index foreign keys by itself; every per-user query filters on user_id.
CREATE INDEX ON phrases (user_id, language);
CREATE INDEX ON slot_words (user_id);
CREATE INDEX ON templates (user_id);
CREATE INDEX ON samples (user_id);
CREATE INDEX ON samples (phrase_id);
CREATE INDEX ON uses (user_id);
CREATE INDEX ON api_calls (user_id, quota, created_at);
CREATE INDEX ON training_attempts (user_id);
CREATE INDEX ON training_reflections (user_id);
